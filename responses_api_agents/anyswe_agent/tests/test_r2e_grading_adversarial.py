import os
import subprocess
import sys

import pytest

from responses_api_agents.anyswe_agent.app import _r2e_expected_resolved, _r2e_parse_log_pytest, _r2e_resolved


def _pytest_log(tmp_path, source, returncode):
    (tmp_path / "test_probe.py").write_text(source)
    env = {k: v for k, v in os.environ.items() if not k.startswith("PYTEST_")}
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-rA", "--color=yes", "test_probe.py"],
        cwd=tmp_path,
        env=env,
        capture_output=True,
        text=True,
    )
    assert result.returncode == returncode, result.stdout + result.stderr
    return result.stdout


@pytest.mark.parametrize("node", ["test_case[PASSED]", "test_PASSED"])
def test_status_word_in_failing_name_does_not_become_pass(node):
    log = f"=== short test summary info ===\nFAILED r2e_tests/test_1.py::{node} - AssertionError\n"
    assert not _r2e_expected_resolved({node: "PASSED"}, log)
    assert _r2e_expected_resolved({node: "FAILED"}, log)


def test_status_word_in_diagnostic_does_not_become_pass():
    log = "=== short test summary info ===\nFAILED r2e_tests/a.py::test_x - AssertionError: expected PASSED\n"
    assert not _r2e_expected_resolved({"test_x": "PASSED"}, log)
    assert _r2e_expected_resolved({"test_x": "FAILED"}, log)


def test_expected_compound_ansi():
    log = "=== short test summary info ===\n\x1b[1;32mPASSED\x1b[0m r2e_tests/a.py::test_x\n"
    assert _r2e_expected_resolved({"\x1b[1;32mtest_x\x1b[0m": "PASSED"}, log)


def test_valid_pytest_parameter_with_closing_bracket(tmp_path):
    log = _pytest_log(
        tmp_path,
        "import pytest\n@pytest.mark.parametrize('value',[0],ids=['a] - b'])\ndef test_x(value):\n    assert True\n",
        0,
    )
    assert _r2e_resolved({"FAIL_TO_PASS": ["test_probe.py::test_x[a] - b]"]}, log)


def test_real_pytest_failure_containing_status_word(tmp_path):
    log = _pytest_log(
        tmp_path,
        "import pytest\n@pytest.mark.parametrize('value',[0],ids=['PASSED'])\ndef test_x(value):\n    assert False\n",
        1,
    )
    assert not _r2e_expected_resolved({"test_x[PASSED]": "PASSED"}, log)
    assert _r2e_expected_resolved({"test_x[PASSED]": "FAILED"}, log)


def test_real_pytest_teardown_error_can_match_expected_error(tmp_path):
    log = _pytest_log(
        tmp_path,
        "import pytest\n@pytest.fixture(autouse=True)\ndef resource():\n    yield\n"
        "    raise RuntimeError('teardown')\ndef test_x():\n    assert True\n",
        1,
    )
    assert _r2e_expected_resolved({"test_x": "ERROR"}, log)
    assert not _r2e_expected_resolved({"test_x": "PASSED"}, log)


@pytest.mark.parametrize("parameter_id", ["a] - b", "a[ - b", "x - y] - z"])
def test_real_pytest_teardown_failure_overrides_passing_parameter(tmp_path, parameter_id):
    log = _pytest_log(
        tmp_path,
        "import pytest\n@pytest.fixture(autouse=True)\ndef resource():\n    yield\n"
        "    raise RuntimeError('teardown failed')\n"
        f"@pytest.mark.parametrize('value',[0],ids=[{parameter_id!r}])\n"
        "def test_x(value):\n    assert True\n",
        1,
    )
    required = {"FAIL_TO_PASS": [f"test_probe.py::test_x[{parameter_id}]"]}
    assert not _r2e_resolved(required, log)
    # Duplicate observations retain the failure even when a retry prints PASSED later.
    summary = log.split("short test summary info", 1)[1].splitlines()[1:-1]
    assert not _r2e_resolved(required, "\n".join(reversed(summary)))


@pytest.mark.parametrize("passing", [True, False])
def test_real_pytest_preserves_upstream_encoded_parameter(tmp_path, passing):
    log = _pytest_log(
        tmp_path,
        "import pytest\n@pytest.mark.parametrize('value',[0],ids=['one::two'])\n"
        f"def test_x(value):\n    assert {passing}\n",
        0 if passing else 1,
    )
    # Golden keys generated by upstream parse_log_pytest replace every ::, including parameter text.
    expected = {"test_x[one.two]": "PASSED" if passing else "FAILED"}
    assert _r2e_parse_log_pytest(log) == expected
    assert _r2e_expected_resolved(expected, log)


def test_real_pytest_expected_failure_with_bracketed_diagnostic(tmp_path):
    log = _pytest_log(
        tmp_path,
        "import pytest\n@pytest.mark.parametrize('value',[0],ids=['one'])\n"
        "def test_x(value):\n    assert [0] == [1]\n",
        1,
    )
    assert _r2e_expected_resolved({"test_x[one]": "FAILED"}, log)
    assert not _r2e_resolved({"FAIL_TO_PASS": ["test_probe.py::test_x[one]"]}, log)


@pytest.mark.parametrize("passing", [True, False])
def test_real_pytest_preserves_legacy_dash_encoding(tmp_path, passing):
    log = _pytest_log(
        tmp_path,
        "import pytest\n@pytest.mark.parametrize('value',[0],ids=['one - two'])\n"
        f"def test_x(value):\n    assert {passing}\n",
        0 if passing else 1,
    )
    # Upstream failure maps have already lost the suffix; passing maps lose it during reward comparison.
    expected = {"test_x[one - two]" if passing else "test_x[one": "PASSED" if passing else "FAILED"}
    assert _r2e_expected_resolved(expected, log)


def test_expected_map_keeps_legacy_phase_order():
    log = "=== short test summary info ===\nFAILED a.py::test_x - failure\nPASSED a.py::test_x\n"
    # Retry/phase aggregation is an upstream contract, distinct from explicit FAIL_TO_PASS matching.
    assert _r2e_expected_resolved({"test_x": "PASSED"}, log)
    assert not _r2e_resolved({"FAIL_TO_PASS": ["a.py::test_x"]}, log)

def _read(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines()]


def test_format_source_row_keeps_the_validated_schema() -> None:
    row = {"id": 7, "wav_filename": "a.wav", "raw_transcription": "r", "transcription": "t"}
    source_row = lid.format_source_row("de_de", row, 4.5, "/mnt/audio", "Pick one: de_de.")
    assert source_row["id"] == "de_de:a.wav" and source_row["expected_answer"] == "de_de"
    assert source_row["audio_path"] == "/mnt/audio/de_de/a.wav" and source_row["subset_for_metrics"] == "de_de"
    assert source_row["messages"] == [
        {"role": "user", "content": "Pick one: de_de.", "audio": {"path": "/mnt/audio/de_de/a.wav", "duration": 4.5}}
    ]
    assert source_row["task_type"] == "FLEURS-LID"
    assert source_row["extra_fields"]["locale_name"] == "German"
    assert source_row["extra_fields"]["lang_group"] == "western_european_we"
    assert source_row["extra_fields"]["source_id"] == 7


def test_prepare_defaults_to_every_available_locale_and_lists_them_in_the_prompt(offline_fleurs: Path) -> None:
    output = lid.prepare()
    rows = _read(output)
    assert [row["id"] for row in rows] == [
        "de_de:d1.wav",
        "de_de:d2.wav",
        "de_de:d3.wav",
        "fr_fr:f1.wav",
        "fr_fr:f2.wav",
    ]
    assert [row["sample_id"] for row in rows] == [f"fleurs-lid:{i}" for i in range(1, 6)]
    assert [row["duration"] for row in rows] == [1.0, 0.5, 1.5, 2.0, 1.0]
    first = rows[0]
    audio_path = Path(first["responses_create_params"]["metadata"]["audio_path"])
    assert audio_path == (lid.DATA_DIR / "audio" / "de_de" / "d1.wav").resolve() and audio_path.is_file()
    (message,) = first["responses_create_params"]["input"]
    assert message["role"] == "user" and message["content"].endswith("nothing else: de_de, fr_fr.")
    assert first["ng_source_row"]["messages"][0]["content"] == message["content"]
    assert first["ng_source_row_sha256"] == audio_manifest.source_hash(first["ng_source_row"])
    assert not list((lid.DATA_DIR / "hf-fleurs").rglob("*.tar.gz")), "tarballs are removed after extraction"
    assert lid.is_prepared_data_current(output)
    assert not lid.is_prepared_data_current(lid.DATA_DIR / "other.jsonl")


def test_prepare_narrows_by_locale_with_the_prompt_following(offline_fleurs: Path) -> None:
    for languages in ("fr_fr", ["fr_fr"]):
        output = lid.prepare(languages=languages)
        rows = _read(output)
        assert [row["id"] for row in rows] == ["fr_fr:f1.wav", "fr_fr:f2.wav"]
        assert all(
            row["responses_create_params"]["input"][0]["content"].endswith("nothing else: fr_fr.") for row in rows
        )
        assert not lid.is_prepared_data_current(output), "narrowed data must be prepared again by default"
    assert not (lid.DATA_DIR / "audio" / "de_de").exists(), "locales outside the selection are not extracted"
    with pytest.raises(ValueError, match="Empty or unknown"):
        lid.prepare(languages="xx_xx")



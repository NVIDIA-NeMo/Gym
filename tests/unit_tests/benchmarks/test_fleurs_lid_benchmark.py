def test_parse_tsv_checks_the_format(tmp_path: Path) -> None:
    def parse(*lines: str):
        path = tmp_path / "x.tsv"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return fleurs_common.parse_tsv(path, "xx_aa")

    ok = "1\ta.wav\tRaw, text.\traw text\tp\t1\tMALE"
    assert parse(ok, "", "2\tb.wav\tR\tr\tp\t1\tFEMALE")[0] == {
        "id": 1,
        "raw_transcription": "Raw, text.",
        "transcription": "raw text",
        "wav_filename": "a.wav",
    }
    for bad, message in [
        ("1\ta.wav\tonly\tthree", "expected 7"),
        ("x\ta.wav\tr\tt\tp\t1\tM", "non-integer"),
        ("1\t../a.wav\tr\tt\tp\t1\tM", "unsafe"),
        ("1\ta.mp3\tr\tt\tp\t1\tM", "unsafe"),
    ]:
        with pytest.raises(ValueError, match=message):
            parse(bad)
    with pytest.raises(ValueError, match="duplicate"):
        parse(ok, ok)



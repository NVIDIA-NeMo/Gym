def test_prepare_rejects_a_drifted_source(offline_fleurs: Path, monkeypatch) -> None:
    name, group, _ = fleurs_common.LOCALES["de_de"]
    monkeypatch.setitem(fleurs_common.LOCALES, "de_de", (name, group, 99))
    with pytest.raises(ValueError, match="row-count drift"):
        lid.prepare(languages="de_de")
    monkeypatch.setitem(fleurs_common.LOCALES, "de_de", (name, group, 3))
    (offline_fleurs / "data" / "de_de" / "audio" / "test.tar.gz").unlink()
    with tarfile.open(offline_fleurs / "data" / "de_de" / "audio" / "test.tar.gz", "w:gz") as archive:
        payload = pcm_wav_bytes(16000)
        info = tarfile.TarInfo("test/d1.wav")
        info.size = len(payload)
        archive.addfile(info, io.BytesIO(payload))
    with pytest.raises(ValueError, match="inventory mismatch"):
        lid.prepare(languages="de_de")

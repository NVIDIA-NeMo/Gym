def is_valid_guess(word: str, word_length: int = 5) -> bool:
    """Check if a word is a valid guess."""
    word = word.lower()
    if len(word) != word_length:
        return False
    if not word.isalpha():
        return False
    return word in WORDLE_VALID_GUESSES

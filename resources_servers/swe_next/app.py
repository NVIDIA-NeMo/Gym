"""Resources server for TIGER-Lab/SWE-Next.

SWE-Next is 2,306 rows, entirely Python, generated by the R2E ("Repo-to-Environment") pipeline:
every row ships its own prebuilt image (``docker_image``), a workdir fixed at ``/testbed``, and a
byte-identical test command across the whole dataset (see ``verification.py``) -- so there is no
per-row test-command construction, only a fixed recipe.

Verification: apply the candidate patch and the dataset's held-out ``test_patch``, run the fixed
R2E test command, and grade against ``expected_output_json`` (a whole-suite PASSED/FAILED/ERROR
snapshot from the golden-patched instance) exactly the way upstream's own
``DockerRuntime._calculate_reward_r2e`` does -- NOT a FAIL_TO_PASS/PASS_TO_PASS check, see
``verification.py``'s module docstring for why.

Set ``is_verifying_golden_patch: true`` to grade the dataset's own patch instead of an agent's,
the dataset-health check: a row whose golden patch does not resolve is a broken row.
"""


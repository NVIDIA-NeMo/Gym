class SWENextResourcesServer(NativeSWESandboxResourcesServer):
    config: SWENextResourcesServerConfig

    def _inputs(self, body: SWENextInstanceRequest, patch: str) -> VerificationInputs:
        return VerificationInputs(
            instance_id=body.instance_id,
            workdir=body.workdir,
            patch=patch,
            test_patch=body.test_patch,
            expected_output_json=body.expected_output_json,
        )

    async def _create_sandbox(
        self,
        body: SWENextInstanceRequest,
        files: dict[str, str] | None = None,
        *,
        session_id: str | None = None,
        setup: Callable[[AsyncSandbox], Awaitable[SessionData]] | None = None,
    ) -> AsyncSandbox:
        global_config_dict = get_global_config_dict()
        provider_config = resolve_provider_config(self.config.sandbox_provider, global_config_dict)
        provider_metadata = resolve_provider_metadata(self.config.sandbox_provider, global_config_dict)

        sandbox_resources = SandboxResources.from_mapping(self.config.sandbox_config.get("resources", {}))
        env = dict(self.config.sandbox_config.get("env", {}))
        if self.config.sandbox_config.get("derive_cpu_env", True):
            env = cpu_cap_env(sandbox_resources.cpu) | env

        spec = SandboxSpec(
            # The row names its own image; there is no repository template to apply.
            image=body.image_ref,
            ttl_s=self.config.sandbox_config.get("ttl_s"),
            ready_timeout_s=self.config.sandbox_config.get("ready_timeout_s"),
            # `/testbed` (`body.workdir`) is a symlink to `/workspace` that the R2E image's own
            # entrypoint normally creates on container start -- the sandbox provider never runs
            # that entrypoint, so `/testbed` does not exist yet and cannot be used as the spec's
            # workdir (every exec validates it against the live filesystem). `/workspace` is the
            # real directory the image bakes in; recreate the symlink ourselves right after start.
            workdir="/workspace",
            env=env,
            files=files or {},
            metadata=provider_metadata
            | self.config.sandbox_config.get("metadata", {})
            | {
                "nemo_gym_agent": self.config.name,
                "instance_id": body.instance_id[:63],
            },
            resources=sandbox_resources,
            provider_options=self.config.sandbox_config.get("provider_options", {}),
        )
        if session_id is not None:
            return await self.start_session_sandbox(session_id, spec, setup=setup, workdir=body.workdir)
        sandbox = AsyncSandbox(provider_config)
        await sandbox.start(spec)
        await sandbox.exec(f"ln -sfn /workspace {shlex.quote(body.workdir)}")
        return sandbox

    async def _stop_sandbox(self, sandbox: AsyncSandbox | None) -> None:
        if sandbox is None:
            return
        try:
            await sandbox.stop()
        except Exception:
            print("Failed to stop SWE-Next sandbox", format_exc(), file=sys.stderr)

    async def _init_git_repo(self, sandbox: AsyncSandbox, workdir: str) -> None:
        """These images have no git history at all -- init one fresh so ``seed_session`` has a
        real base commit to diff the agent's changes against, and the anti-cheat scrub has an
        actual repo to act on.
        """
        result = await sandbox.exec(
            f"cd {shlex.quote(workdir)} && git init -q "
            f"&& git config user.email nemo-gym@nvidia.com && git config user.name nemo-gym "
            f"&& git add -A && git commit -q -m 'nemo_gym: initial snapshot' --allow-empty"
        )
        if result.return_code != 0:
            print(f"Failed to init git repo at {workdir}: {result.stdout}\n{result.stderr}", file=sys.stderr)

    async def _pristine_untracked_files(self, sandbox: AsyncSandbox, workdir: str) -> frozenset[str]:
        """List of files ``workdir`` holds untracked before the agent touches it."""
        try:
            result = await sandbox.exec(f"git -C {shlex.quote(workdir)} ls-files --others --exclude-standard")
            if result.return_code != 0:
                print(f"Failed to list pristine untracked files: {result.stderr}", file=sys.stderr)
                return frozenset()
            return frozenset(line.strip() for line in (result.stdout or "").splitlines() if line.strip())
        except Exception:
            print("Failed to list pristine untracked files", format_exc(), file=sys.stderr)
            return frozenset()

    async def _extract_model_patch(self, session_id: str, workdir: str, base_commit: str) -> PatchCapture:
        """Capture the agent's patch; the caller ends the session after retaining the result."""
        original_sandbox = self.require_session_sandbox(session_id)
        pristine_untracked = frozenset(self.session_data(session_id).get("pristine_untracked") or [])
        return await capture_model_patch(
            original_sandbox,
            workdir,
            base_commit,
            mode=self.config.patch_capture_mode,
            pristine_untracked=pristine_untracked,
            drop_sections=drop_patch_sections,
        )

    async def seed_session(self, request: Request, body: SWENextSeedSessionRequest) -> SWENextSeedSessionResponse:
        """Start the instance's image so an agent can work in it."""
        session_id = request.session[SESSION_ID_KEY]
        sandbox = self.session_sandbox(session_id)
        if sandbox is None:

            async def setup(sandbox: AsyncSandbox) -> SessionData:
                # The session-owner path must prepare the image just as grading sandboxes do.
                await sandbox.exec(f"ln -sfn /workspace {shlex.quote(body.workdir)}")
                await hide_grading_artifacts(sandbox, body.workdir)
                await self._init_git_repo(sandbox, body.workdir)
                if self.config.apply_anti_cheating:
                    await apply_anti_cheat_setup(sandbox, body.workdir, body.instance_id, "swe_next")
                # The anti-cheat scrub leaves no committer identity, so the agent's `git commit` would fail.
                await prepare_git_for_commits(sandbox, body.workdir, "swe_next")

                head_result = await sandbox.exec(f"git -C {shlex.quote(body.workdir)} rev-parse HEAD")
                base_commit = (head_result.stdout or "").strip()
                pristine_untracked = await self._pristine_untracked_files(sandbox, body.workdir)
                return {"pristine_untracked": sorted(pristine_untracked), "base_commit": base_commit}

            sandbox = await self._create_sandbox(body, session_id=session_id, setup=setup)
        # A restored session already has its prepared checkout and verification metadata.
        return SWENextSeedSessionResponse(sandbox_handle=str(sandbox.handle.sandbox_id))

    async def verify(self, request: Request, body: SWENextVerifyRequest) -> SWENextVerifyResponse:
        try:
            prepared = await self._capture_patch(request.session[SESSION_ID_KEY], body)
        finally:
            await self.end_session_sandbox(request.session[SESSION_ID_KEY])
        return await self._evaluate_patch(request, body, prepared)

    async def prepare_verify(self, request: Request, body: SWENextVerifyRequest) -> NativePreparedPatch:
        return await self.prepare_verification(
            request, partial(self._capture_patch, request.session[SESSION_ID_KEY], body)
        )

    async def verify_prepared(self, request: Request, body: SWENextPreparedVerifyRequest) -> SWENextVerifyResponse:
        self.forget_prepared_verification(request)
        verify_body = SWENextVerifyRequest.model_validate(
            body.model_dump(exclude={"capture", "extraction_error", "model_patch"})
        )
        return await self._evaluate_patch(request, verify_body, body)

    async def _capture_patch(self, session_id: str, body: SWENextVerifyRequest) -> NativePreparedPatch:
        extraction_error = None
        mode = self.config.patch_capture_mode
        if self.config.is_verifying_golden_patch:
            capture = PatchCapture.static(body.patch, mode, "golden")
        else:
            base_commit = self.session_data(session_id).get("base_commit") or ""
            if not base_commit:
                capture = PatchCapture.static("", mode, "none")
                extraction_error = "Failed to extract model patch: no base commit recorded (seed_session did not run for this session)"
            else:
                try:
                    capture = await self._extract_model_patch(session_id, body.workdir, base_commit)
                except Exception as exc:
                    capture = PatchCapture.static("", mode, "none")
                    extraction_error = f"Failed to extract model patch: {exc}"
        return NativePreparedPatch(capture=capture, extraction_error=extraction_error)

    async def _evaluate_patch(
        self, request: Request, body: SWENextVerifyRequest, prepared: NativePreparedPatch
    ) -> SWENextVerifyResponse:
        capture = prepared.capture
        extraction_error = prepared.extraction_error
        patch = capture.patch

        inputs = self._inputs(body, patch)
        log_dir = Path(__file__).parent / "logs" / body.instance_id / uuid4().hex

        files = verification_files(inputs)
        attempts = 1 + max(self.config.inconclusive_verification_retries, 0)
        start_time_taken = 0.0
        verification_time_taken = 0.0
        result = VerificationResult(
            completed=False,
            resolved=False,
            patch_applied=False,
            test_results=None,
            test_output="",
            error="unattempted",
        )
        for attempt in range(1, attempts + 1):
            sandbox: AsyncSandbox | None = None
            started = time()
            try:
                sandbox = await self._create_sandbox(body, files=files)
                start_time_taken = time() - started
                verification_started = time()
                result = await run_verification(
                    sandbox=sandbox,
                    inputs=inputs,
                    timeout_s=self.config.evaluation_timeout,
                    log_dir=log_dir,
                )
                verification_time_taken = time() - verification_started
            except Exception as exc:
                start_time_taken = time() - started
                verification_time_taken = 0.0
                result = VerificationResult(
                    completed=False,
                    resolved=False,
                    patch_applied=False,
                    test_results=None,
                    test_output="",
                    error=f"Verification failed: {exc}",
                )
            finally:
                await self._stop_sandbox(sandbox)
            if result.completed:
                break
            if attempt < attempts:
                print(
                    f"[swe_next] {body.instance_id}: inconclusive ({result.error}); "
                    f"retrying on a fresh sandbox ({attempt}/{attempts - 1})",
                    flush=True,
                )

        return SWENextVerifyResponse.model_validate(
            body.model_dump()
            | {
                # An unresolved-but-completed run is a real 0. An incomplete run is also 0, but
                # evaluation_completed distinguishes them so a broken row is not read as a hard task.
                "reward": 1.0 if result.resolved else 0.0,
                "evaluation_completed": result.completed,
                "resolved": result.resolved,
                "patch_applied": result.patch_applied,
                "instance_id": body.instance_id,
                "language": body.language,
                "test_results": result.test_results,
                "test_output": result.test_output[-100_000:],
                "error": extraction_error or result.error,
                "eval_sandbox_start_time_taken": start_time_taken,
                "patch_verification_time_taken": verification_time_taken,
                **capture.response_fields(self.config.include_model_patch_in_response),
            }
        )


if __name__ == "__main__":
    SWENextResourcesServer.run_webserver()
elif is_nemo_gym_fastapi_entrypoint(__file__):
    # Required whenever num_workers > 1. Multi-worker uvicorn re-imports this entrypoint BY PATH
    # in each forked child and expects a module-level `app`; without it every child exits, and
    # uvicorn responds by stopping the parent. The server then never binds, so the symptom is not
    # an import error but a flood of connection failures from clients talking to a dead port.
    app = SWENextResourcesServer.run_webserver()  # noqa: F401

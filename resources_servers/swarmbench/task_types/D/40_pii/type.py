def person(seed, slot):
    """Unique fictional name for global slot id (bijection on FIRST x LAST, shifted by seed)."""
    k = (slot * 7919 + seed * 131 + 17) % COMBOS
    return f"{FIRST[k % len(FIRST)]} {LAST[k // len(FIRST)]}"


def luhn_ok(digits):
    s = 0
    for i, ch in enumerate(reversed(digits)):
        d = int(ch)
        if i % 2 == 1:
            d *= 2
            if d > 9:
                d -= 9
        s += d
    return s % 10 == 0


def make_card(rng, valid):
    body = str(rng.choice([4, 5])) + "".join(str(rng.randint(0, 9)) for _ in range(14))
    check = next(c for c in range(10) if luhn_ok(body + str(c)))
    if not valid:
        check = (check + rng.randint(1, 9)) % 10
    d = body + str(check)
    return " ".join(d[i:i + 4] for i in range(0, 16, 4))


def make_phone(rng):
    return f"({rng.randint(201, 989)}) 555-{rng.randint(100, 9999):04d}"


def make_id(rng):
    a = rng.randint(100, 899)
    a = 667 if a == 666 else a
    return f"{a:03d}-{rng.randint(10, 99):02d}-{rng.randint(1000, 9999):04d}"


def make_address(rng):
    city, st = rng.choice(CITIES)
    return f"{rng.randint(10, 9899)} {rng.choice(STREETS)} {rng.choice(SUFFIXES)}, {city}, {st} {rng.randint(10001, 99899):05d}"


def make_dob(rng):
    return dt.date(1930, 1, 1) + dt.timedelta(days=rng.randint(0, 27000))


def dob_text(d):
    return f"{d.strftime('%B')} {d.day}, {d.year}"


def make_isbn(rng):
    core = "9780" + "".join(str(rng.randint(0, 9)) for _ in range(8))
    s = sum(int(c) * (1 if i % 2 == 0 else 3) for i, c in enumerate(core))
    full = core + str((10 - s % 10) % 10)
    return f"{full[:3]}-{full[3]}-{full[4:8]}-{full[8:12]}-{full[12]}"


def company(rng):
    return f"{rng.choice(CO_A)} {rng.choice(CO_B)} {rng.choice(CO_C)}"



SYN = {"name": "name", "full_name": "name", "person": "name", "phone": "phone", "phone_number": "phone",
       "telephone": "phone", "email": "email", "email_address": "email", "address": "address",
       "home_address": "address", "dob": "dob", "date_of_birth": "dob", "birth_date": "dob", "gov_id": "gov_id",
       "government_id": "gov_id", "ssn": "gov_id", "id": "gov_id", "card": "card", "card_number": "card",
       "payment_card": "card", "credit_card": "card"}
MONTHS = {m: k for k, m in enumerate(["january", "february", "march", "april", "may", "june", "july", "august",
                                      "september", "october", "november", "december"], 1)}


def norm_value(t, v):
    v = str(v).strip()
    if t in ("phone", "gov_id", "card"):
        return re.sub(r"\D", "", v)
    if t == "email":
        return v.lower().strip(" .<>")
    if t == "dob":
        m = re.fullmatch(r"(\d{4})-(\d{1,2})-(\d{1,2})", v)
        if m:
            y, mo, d = map(int, m.groups())
        else:
            m = re.fullmatch(r"([A-Za-z]+)\.? (\d{1,2}),? (\d{4})", v)
            if not m or m.group(1).lower() not in MONTHS:
                return v.lower()
            y, mo, d = int(m.group(3)), MONTHS[m.group(1).lower()], int(m.group(2))
        try:
            return dt.date(y, mo, d).isoformat()
        except ValueError:
            return v
    return " ".join(re.sub(r"[^a-z0-9 ]", " ", v.lower()).split())


def norm_item(t, v):
    t = SYN.get(re.sub(r"[^a-z_]", "", str(t).strip().lower().replace(" ", "_")), str(t).strip().lower())
    return t, norm_value(t, v)


def canon_doc(k):
    m = re.fullmatch(r"\s*DOC-?0*(\d{1,5})\s*", str(k), re.I)
    return f"DOC-{int(m.group(1)):04d}" if m else None


def parse_answer(answer):
    obj = common.last_json(answer, lambda o: isinstance(o, dict) and any(canon_doc(k) for k in o))
    out = {}
    for k, v in (obj or {}).items():
        d = canon_doc(k)
        if not d or not isinstance(v, list):
            continue
        items = set()
        for it in v:
            if isinstance(it, dict) and "type" in it and "value" in it:
                items.add(norm_item(it["type"], it["value"]))
        out[d] = items
    return out


def score(task, answer):
    g = common.gold_of(task)["docs"]
    p = parse_answer(answer)
    ok, part = 0, 0.0
    for d, gd in g.items():
        gs = {norm_item(t, v) for t, v in gd["items"]}
        if d not in p:
            continue
        ok += p[d] == gs
        part += common.f1(p[d], gs)[0]
    n = len(g)
    return {"score": ok / n, "score_exact": float(ok == n), "score_partial": part / n, "n_correct": ok, "n_units": n}

def _doc(i, seed):
    """One document: real chunk + planted passages. Returns (doc, gold items, officials, consents, kinds)."""
    rng = random.Random(f"pii:{seed}:{i}")
    ch = chunks()[rng.randrange(len(chunks()))]
    fill = lambda key, **kw: common.fill(rng.choice(T[key]), **kw)  # noqa: E731
    slot = iter(range(i * SLOTS, (i + 1) * SLOTS))
    passages, gold, officials, consents, kinds = [], set(), [], [], []
    n_priv = 0 if rng.random() < 0.12 else rng.choice([1, 1, 2, 2, 3])
    n_off = rng.choice([0, 1, 1, 2])
    n_bus = rng.choice([0, 1])
    n_num = rng.choice([0, 1, 1, 2])
    nums = [rng.choice(["d_case", "d_part", "d_isbn"]) for _ in range(n_num)]
    traps = n_off + n_bus + sum(k != "d_isbn" for k in nums)  # an ISBN has its own shape: not a trap
    sem = 0  # semantic traps: only reading the passage tells them apart (no pattern, no list lookup)
    for _ in range(n_priv):
        name = person(seed, next(slot))
        status = rng.choices(["plain", "granted", "withdrawn"], [0.55, 0.25, 0.2])[0]
        pk = rng.sample(["contact", "home", "id", "card", "via"], rng.choice([1, 1, 2]))
        items = {("name", name)}
        for k in pk:
            if k == "contact":
                ph = make_phone(rng)
                em = f"{name.split()[0].lower()}.{name.split()[1].lower()}{rng.randint(2, 98)}@{rng.choice(DOMAINS)}"
                passages.append(fill("p_contact", name=name, phone=ph, email=em))
                items |= {("phone", ph), ("email", em)}
            elif k == "home":
                ad, db = make_address(rng), make_dob(rng)
                passages.append(fill("p_home", name=name, address=ad, dob=dob_text(db)))
                items |= {("address", ad), ("dob", db.isoformat())}
            elif k == "via":
                passages.append(fill("p_via_business", name=name, phone=make_phone(rng), company=company(rng)))
                kinds.append("via_business")
                sem += status != "granted"  # a granted person's passage is dropped whole: no trap left
            elif k == "id":
                g = make_id(rng)
                passages.append(fill("p_id", name=name, id=g))
                items.add(("gov_id", g))
            else:
                valid = rng.random() < 0.55
                c = make_card(rng, valid)
                passages.append(fill("p_card", name=name, card=c))
                if valid:
                    items.add(("card", c))
                else:
                    kinds.append("luhn_fail")
                    traps += 1
        if status != "plain":
            consents.append((name, status))
            kinds.append("consent_" + status)
            traps += status == "granted"  # withdrawn reads like no consent at all: not a trap for a careless reader
        if status != "granted":
            gold |= items
    while traps < 2:
        n_off += 1
        traps += 1
    if sem == 0 and rng.random() < 0.97:
        if rng.random() < 0.5:
            name = person(seed, next(slot))
            o = (name, rng.choice(TITLES), rng.choice(AGENCIES), make_phone(rng))
            officials.append(o)
            home = make_phone(rng)
            passages.append(fill("p_official_private", title=o[1], name=name, agency=o[2], phone=home))
            gold |= {("name", name), ("phone", home)}
            kinds.append("official_private")
        else:
            passages.append(fill("d_sample", name=person(seed, next(slot)), id=make_id(rng)))
            kinds.append("sample")
    for _ in range(n_off):
        name = person(seed, next(slot))
        o = (name, rng.choice(TITLES), rng.choice(AGENCIES), make_phone(rng))
        officials.append(o)
        passages.append(fill("d_official", title=o[1], name=name, agency=o[2], phone=o[3]))
        kinds.append("official")
    for _ in range(n_bus):
        co = company(rng)
        slug = re.sub(r"[^a-z]", "", co.split()[0].lower() + co.split()[1].lower())
        passages.append(fill("d_business", company=co, phone=make_phone(rng), email=f"{rng.choice(ROLES)}@{slug}.example",
                             address=make_address(rng)))
        kinds.append("business")
    for k in nums:
        passages.append(fill(k, case=make_id(rng), part=make_id(rng), isbn=make_isbn(rng)))
        kinds.append(k[2:])
    rng.shuffle(passages)
    paras = list(ch["paras"])
    pos = sorted(rng.randint(2, len(paras)) for _ in passages)
    for k, p in reversed(list(zip(pos, passages))):
        paras.insert(k, p)
    doc = {"id": f"DOC-{i + 1:04d}", "title": ch["book"], "src": ch["src"], "paras": paras}
    return doc, sorted(gold), officials, consents, kinds


def generate(n, seed, out_dir):
    assert n <= MAX_DOCS
    docs, gold, officials, consents = [], {}, [], []
    for i in range(n):
        d, g, o, c, k = _doc(i, seed)
        docs.append(d)
        gold[d["id"]] = {"items": [list(x) for x in g], "kinds": k}
        officials += o
        consents += c
    frng = random.Random(f"pii-fill:{seed}:{n}")
    for j in range(max(10, n // 2)):
        officials.append((person(seed, MAX_DOCS * SLOTS + j), frng.choice(TITLES), frng.choice(AGENCIES),
                          make_phone(frng)))
    for j in range(max(10, n // 2)):
        consents.append((person(seed, MAX_DOCS * SLOTS + 500 + j), frng.choice(["granted", "withdrawn"])))
    key = lambda x: (x[0].split()[1], x[0].split()[0])  # noqa: E731
    directory = [f"{o[0]} | {o[1]} | {o[2][4:] if o[2].startswith('the ') else o[2]} | {o[3]}"
                 for o in sorted(officials, key=key)]
    register = []
    for c in sorted(consents, key=key):
        r = random.Random(f"pii-reg:{seed}:{c[0]}")
        register.append(f"{c[0]} | {c[1]} | {dt.date(2019, 1, 1) + dt.timedelta(days=r.randint(0, 2000))} | "
                        f"CR-{r.randint(10000, 99999)}")
    world = {"documents.json": docs, "directory.json": directory, "register.json": register}
    prompt = "\n\n".join([common.fill(T["intro"], program=T["program"], n=n, first=docs[0]["id"], last=docs[-1]["id"]),
                          rules_text(example(docs[0]["id"], docs[-1]["id"] if n > 1 else None))])
    return common.finish(TYPE_ID, n, seed, out_dir, prompt, {"docs": gold}, TIERS, files=world)


def example(a, b=None):
    ex = {a: [{"type": "email", "value": "<as written in the document>"}]}
    if b:
        ex[b] = []
    return json.dumps(ex)


def rules_text(ex):
    return "\n\n".join([T[k] for k in ("rule_report", "rule_officials", "rule_private_capacity", "rule_business",
                                       "rule_numbers", "rule_samples",
                                       "rule_luhn",
                                       "rule_consent", "rule_source", "rule_format")] +
                       [common.fill(T["answer_line"], example=ex)])


# ---------- tools ----------
_cache, _lock = {}, threading.Lock()


def _world(world_dir):
    with _lock:
        if world_dir not in _cache:
            p = Path(world_dir)
            docs = json.loads((p / "documents.json").read_text())
            _cache[world_dir] = ({d["id"]: d for d in docs}, [d["id"] for d in docs],
                                 json.loads((p / "directory.json").read_text()),
                                 json.loads((p / "register.json").read_text()))
        return _cache[world_dir]


def _page(head, rows, off, lim, what):
    out, size = [], len(head)
    for r in rows[off:off + lim]:
        if out and size + len(r) + 1 > 7500:
            break
        out.append(r)
        size += len(r) + 1
    nxt = off + len(out)
    more = f"\n({what} {off}-{nxt - 1} of {len(rows)}; next offset {nxt})" if nxt < len(rows) else ""
    return head + "\n" + "\n".join(out) + more


def _doc_of(by, a):
    d = str(a["doc_id"]).strip().upper()
    if re.fullmatch(r"DOC-?\d+", d):
        d = f"DOC-{int(re.sub(r'[^0-9]', '', d)):04d}"
    if d not in by:
        raise KeyError(f"unknown document {d}")
    return by[d]


def tools(world_dir):
    D = T["tools"]
    S, I = {"type": "string"}, {"type": "integer"}

    def list_documents(a):
        by, order, _, _ = _world(world_dir)
        off, lim = common.page_args(a, 100, 200)
        return _page("document | source title | paragraphs",
                     [f"{x} | {by[x]['title']} | {len(by[x]['paras'])}" for x in order], off, lim, "documents")

    def read_document(a):
        by, _, _, _ = _world(world_dir)
        d = _doc_of(by, a)
        start = int(a.get("start") or 1)
        if start < 1 or start > len(d["paras"]):
            raise ValueError(f"start must be 1..{len(d['paras'])}")
        out, size, k = [], 0, start
        while k <= len(d["paras"]):
            line = f"[{k}] {d['paras'][k - 1]}"
            if out and size + len(line) > 7200:
                break
            out.append(line)
            size += len(line) + 1
            k += 1
        tail = f"\n(paragraphs {start}-{k - 1} of {len(d['paras'])}; next start {k})" if k <= len(d["paras"]) else \
            f"\n(paragraphs {start}-{k - 1} of {len(d['paras'])}; end of document)"
        return f"{d['id']} ({d['title']})\n" + "\n".join(out) + tail

    def search_document(a):
        by, _, _, _ = _world(world_dir)
        d = _doc_of(by, a)
        q = str(a.get("query") or "").strip().lower()
        if not q:
            raise ValueError("query is required")
        hits = [f"[{k}] {p[:300]}" for k, p in enumerate(d["paras"], 1) if q in p.lower()]
        return f"{len(hits)} paragraphs" + (" (first 20 shown)" if len(hits) > 20 else "") + "\n" + "\n".join(hits[:20])

    def lister(idx, head_key):
        def f(a):
            rows = _world(world_dir)[idx]
            off, lim = common.page_args(a, 100, 200)
            return _page(T[head_key], rows, off, lim, "rows")
        return f

    def searcher(idx):
        def f(a):
            rows = _world(world_dir)[idx]
            q = str(a.get("query") or "").strip().lower()
            if not q:
                raise ValueError("query is required")
            hits = [r for r in rows if q in r.lower()]
            return f"{len(hits)} rows" + (" (first 30 shown)" if len(hits) > 30 else "") + "\n" + "\n".join(hits[:30])
        return f

    pg = {"offset": I, "limit": I}
    return [common.tool("list_documents", D["list_documents"], pg, [], list_documents),
            common.tool("read_document", D["read_document"], {"doc_id": S, "start": I}, ["doc_id"], read_document),
            common.tool("search_document", D["search_document"], {"doc_id": S, "query": S}, ["doc_id", "query"],
                        search_document),
            common.tool("read_directory", D["read_directory"], pg, [], lister(2, "directory_header")),
            common.tool("search_directory", D["search_directory"], {"query": S}, ["query"], searcher(2)),
            common.tool("read_register", D["read_register"], pg, [], lister(3, "register_header")),
            common.tool("search_register", D["search_register"], {"query": S}, ["query"], searcher(3)),
            common.calculator_tool(T["calculator"])]



"""Task-data schema for the vlm_eval_kit server.

Explicitly multi-benchmark: many VLMEvalKit benchmarks run through one server, and verify()
dispatches ``getattr(self, f"_score_{benchmark_name}")``, so the benchmark-name value space is
open (adding a scorer method adds a valid value) and a discriminated union would over-close it.
This schema types the stable envelope (``benchmark_name``, ``category``, ``answer``) required by
``VLMEvalKitVerifyRequest`` (app.py:35, ``extra="allow"``) and keeps the per-benchmark
extras optional: committed example.jsonl contains only OCRBench rows (``answer`` is a list[str]);
MMBench_DEV_EN_V11 rows are GENERATED by prepare_data.py (not committed) and add
``choices``/``group``/``group_size`` with a scalar-str ``answer``. ``answer`` therefore stays
``Any``, matching the wire. Rows embed base64 data-URI images inside responses_create_params.
"""

from typing import Any, Dict, Optional

from pydantic import BaseModel, ConfigDict, Field


class TaskData(BaseModel):
    model_config = ConfigDict(extra="allow")

    benchmark_name: str = Field(
        description=(
            "VLMEvalKit benchmark this row belongs to (e.g. 'OCRBench', 'MMBench_DEV_EN_V11'); "
            "dispatches verify() to _score_<benchmark_name> (AttributeError on unknown values) and "
            "keys per-benchmark aggregation in compute_metrics."
        ),
        json_schema_extra={"consumed_by": ["verify", "metrics"]},
    )
    category: str = Field(
        description=(
            "Benchmark-specific category label (e.g. 'Regular Text Recognition'); selects OCRBench's "
            "handwritten-math normalization branch and names the per-category reward key."
        ),
        json_schema_extra={"consumed_by": ["verify", "metrics"]},
    )
    answer: Any = Field(
        description=(
            "Gold answer; type varies per benchmark (list[str] of acceptable substrings for OCRBench, "
            "scalar str option letter for MMBench). Wire type is Any; required."
        ),
        json_schema_extra={"consumed_by": ["verify"]},
    )
    choices: Optional[Dict[str, Any]] = Field(
        default=None,
        description=(
            "MMBench-only: option-letter -> option-text mapping fed to vlmeval's can_infer; an untyped "
            "extra on today's wire. Absent from OCRBench rows."
        ),
        json_schema_extra={"consumed_by": ["verify"]},
    )
    group: Optional[int] = Field(
        default=None,
        description=(
            "MMBench-only: circular-evaluation group id keying the group-reward Coordinator (all "
            "rollouts of a group must agree for reward 1); untyped extra on today's wire."
        ),
        json_schema_extra={"consumed_by": ["verify", "metrics"]},
    )
    group_size: Optional[int] = Field(
        default=None,
        description=(
            "MMBench-only: number of rows in the circular-evaluation group; the Coordinator releases "
            "the group reward once this many verifications arrive. Untyped extra on today's wire."
        ),
        json_schema_extra={"consumed_by": ["verify"]},
    )

"""Rewrite the task template's two requirements.txt files from the Resources Server's uv.lock.

The tools sidecar and the verifier install their packages from PyPI in every episode. Each file pins every package,
transitive ones included, to the version in ``resources_servers/workplace_assistant/uv.lock`` and carries its hashes,
so the tools and ``is_correct`` run on the same pandas, numpy and pyarrow as the Resources Server, and an install
cannot drift. pyarrow is listed because the Resources Server's environment has it: pandas 3 then stores strings with
pyarrow, and the sidecar and verifier should too.

    python resources_servers/workplace_assistant/harbor/pin_requirements.py

Needs ``uv`` on PATH and access to PyPI.
"""

import subprocess
import tempfile
import tomllib
from pathlib import Path


HARBOR_DIR = Path(__file__).resolve().parent
LOCK = HARBOR_DIR.parent / "uv.lock"
TEMPLATE = HARBOR_DIR / "task-template"
# The packages each sandbox imports directly; everything else comes in as their dependencies.
TOOLS = ["pandas", "numpy", "pyarrow", "mcp", "fastapi", "pydantic", "starlette", "uvicorn"]
GRADER = ["pandas", "numpy", "pyarrow"]
# The images are Linux x86_64 with CPython 3.13 (ghcr.io/astral-sh/uv:python3.13-bookworm-slim).
PLATFORM = ["--python-version", "3.13", "--python-platform", "x86_64-manylinux_2_28"]
HEADER = (
    "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Generated by harbor/pin_requirements.py from resources_servers/workplace_assistant/uv.lock ({}); do not edit.\n"
)


def lock_versions() -> dict[str, str]:
    packages = tomllib.loads(LOCK.read_text())["package"]
    return {package["name"]: package["version"] for package in packages if "version" in package}


def compile_requirements(direct: list[str], versions: dict[str, str], output: Path, purpose: str) -> None:
    with tempfile.TemporaryDirectory() as scratch:
        constraints = Path(scratch) / "constraints.txt"
        constraints.write_text("".join(f"{name}=={version}\n" for name, version in sorted(versions.items())))
        requested = Path(scratch) / "requirements.in"
        requested.write_text("".join(f"{name}\n" for name in direct))
        compiled = subprocess.run(
            ["uv", "pip", "compile", str(requested), "--constraint", str(constraints), "--generate-hashes"]
            + ["--no-header", "--no-annotate", "--quiet", *PLATFORM],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    pinned = {line.split("==")[0]: line.split("==")[1].split()[0] for line in compiled.splitlines() if "==" in line}
    unlocked = sorted(name for name, version in pinned.items() if versions.get(name) != version)
    if unlocked:
        raise SystemExit(f"{output}: versions not taken from uv.lock: {unlocked}")
    output.write_text(HEADER.format(purpose) + compiled)
    print(f"{output}: {len(pinned)} packages")


def main() -> None:
    versions = lock_versions()
    compile_requirements(TOOLS, versions, TEMPLATE / "environment" / "requirements.txt", "tools sidecar")
    compile_requirements(GRADER, versions, TEMPLATE / "tests" / "requirements.txt", "verifier")


if __name__ == "__main__":
    main()

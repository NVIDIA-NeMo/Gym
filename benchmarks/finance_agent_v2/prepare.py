"""Prepare the finance_agent_v2 (FABv2) benchmark data.

The ``gym eval prepare`` entry point, which also converts an explicit file via
``--input/--output``.

Prompts and tool schemas come from the upstream Vals ``finance_agent`` package, read
from the committed ``upstream_spec.json`` snapshot rather than imported: that package
is installed only in the resource server's venv, while ``gym eval prepare`` imports
this module into the root ``gym`` process. The server's
``scripts/export_upstream_spec.py`` regenerates the snapshot and its
``tests/test_upstream_spec.py`` fails when it drifts from the installed package.

The ``rubric`` is copied through verbatim, including the ``modifiers`` carrying
``severity`` and ``category: must_pass``: it is the scoring input, so any edit to it
changes scores. The judge never sees the modifiers — they are applied afterwards by
``app.py`` when aggregating verdicts into Partial Credit. ``expected_answer`` is a
readable join of the criteria, kept for compatibility and read by nothing.

Input precedence for ``prepare()``, under ``data/``: ``labeled.jsonl``,
``public.jsonl``, ``public.txt``, ``public.csv``; if none exist, the public CSV is
downloaded from ``CSV_URL``. Sources without a rubric are a dry run — ``/verify``
returns reward 0 so the agent + tools path can be validated before labels exist.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
import urllib.request
from pathlib import Path


ENV_DIR = Path(__file__).parent
DATA_DIR = ENV_DIR / "data"
OUTPUT_FPATH = DATA_DIR / "vals_v2_public_27q.jsonl"

# Must match the benchmark config's `jsonl_fpath`. Anchored to the CWD, not to
# __file__: Path.absolute() does not resolve symlinks, so on a symlinked checkout an
# __file__-anchored return fails the CLI's `output == jsonl_fpath` check.
_BENCHMARK_REL_FPATH = "benchmarks/finance_agent_v2/data/vals_v2_public_27q.jsonl"

# Pinned to the commit the tools are installed from (see the server's
# requirements.txt), not a branch: these criteria are the scoring input, so tracking
# `main` would let an upstream edit move scores between runs of identical code.
_UPSTREAM_SHA = "bb460b524472ae0955abdf243bbbac06958dc8c9"  # pragma: allowlist secret
CSV_URL = f"https://raw.githubusercontent.com/vals-ai/finance-agent-v2/{_UPSTREAM_SHA}/data/public.csv"

# Generated by the resource server's scripts/export_upstream_spec.py.
SPEC_FPATH = ENV_DIR / "upstream_spec.json"

# Rubric JSON strings can be long; raise the CSV field cap.
csv.field_size_limit(10_000_000)


def _load_upstream_spec() -> dict:
    """Load the snapshot, refusing to run if it predates the pinned commit.

    Bumping ``_UPSTREAM_SHA`` without re-exporting would pair the new commit's
    questions with the old commit's prompts: a dataset that runs normally and is
    comparable to nothing.
    """
    if not SPEC_FPATH.exists():
        raise FileNotFoundError(
            f"missing {SPEC_FPATH}. Generate it from the resource server venv:\n"
            "  cd resources_servers/finance_agent_v2 && "
            "source .venv/bin/activate && python scripts/export_upstream_spec.py"
        )
    spec = json.loads(SPEC_FPATH.read_text(encoding="utf-8"))
    if spec.get("upstream_commit_id") != _UPSTREAM_SHA:
        raise ValueError(
            f"{SPEC_FPATH} was exported from upstream commit {spec.get('upstream_commit_id')}, "
            f"but this benchmark is pinned to {_UPSTREAM_SHA}. Re-run "
            "`python scripts/export_upstream_spec.py` from the resource server venv."
        )
    return spec


_SPEC = _load_upstream_spec()

SYSTEM_PROMPT: str = _SPEC["system_prompt"]
QUESTION_PROMPT: str = _SPEC["question_prompt"]
VALID_TOOLS: tuple[str, ...] = tuple(_SPEC["valid_tools"])


def build_tools(tool_names: list[str] | None = None) -> list[dict]:
    """Build the full v2 tool set (selected tools + submit_final_result)."""
    names = list(tool_names) if tool_names is not None else list(VALID_TOOLS)
    tools = [_SPEC["tools"][name] for name in names]
    tools.append(_SPEC["tools"][_SPEC["submit_tool"]])
    # Deep copy: every sample embeds these dicts, so sharing them would let one
    # in-place edit leak across the dataset.
    return json.loads(json.dumps(tools))


def parse_rubric(raw_rubric) -> list[dict]:
    """Normalize a rubric (JSON string, list, or dict) into a list of checks.

    Criteria and operators are copied verbatim — they are the scoring input, so any
    rewording changes scores. ``modifiers`` is copied whole rather than flattened so
    a key upstream adds later reaches the scorer without a change here; it is absent
    on pre-Aug-2026 exports, where app.py falls back to unweighted and ungated.
    """
    if not raw_rubric:
        return []
    if isinstance(raw_rubric, str):
        if not raw_rubric.strip():
            return []
        checks = json.loads(raw_rubric)
    else:
        checks = raw_rubric
    if isinstance(checks, dict):
        checks = [checks]

    parsed: list[dict] = []
    for check in checks:
        entry = {
            "operator": (check.get("operator") or "").strip(),
            "criteria": check.get("criteria", ""),
        }
        modifiers = check.get("modifiers")
        if isinstance(modifiers, dict) and modifiers:
            entry["modifiers"] = modifiers
        parsed.append(entry)
    return parsed


def build_expected_answer(rubric: list[dict]) -> str:
    """Join the rubric criteria into a readable reference answer.

    The public CSV has no gold answer; each criterion is a required fact. Read by
    nothing since scoring moved to per-criterion judging.
    """
    criteria = [str(c.get("criteria", "")).strip() for c in rubric]
    criteria = [c for c in criteria if c]
    if not criteria:
        return ""
    return "A complete answer must establish all of the following:\n" + "\n".join(f"- {c}" for c in criteria)


def _maybe_int(value) -> int | None:
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return None


def _convert_row(row: dict, tools: list[dict]) -> dict | None:
    """Wrap one input row into Gym benchmark format with v2 prompts + tools.

    Accepts raw Vals CSV column names (``Question``, ``Rubric``, ...) and lowercase
    JSONL keys alike.
    """
    question = (row.get("question") or row.get("Question") or row.get("problem") or row.get("prompt") or "").strip()
    if not question:
        return None

    raw_rubric = row.get("rubric") if row.get("rubric") is not None else row.get("Rubric")
    rubric = parse_rubric(raw_rubric)

    expected = row.get("expected_answer")
    if not expected:
        expected = build_expected_answer(rubric) or None

    question_type = (row.get("question_type") or row.get("Question Type") or "").strip() or None
    expert_raw = row.get("expert_time_mins")
    if expert_raw is None:
        expert_raw = row.get("Expert time (mins)")

    return {
        "question": question,
        "question_type": question_type,
        "expert_time_mins": _maybe_int(expert_raw),
        "expected_answer": expected,
        "rubric": json.dumps(rubric),
        "responses_create_params": {
            "input": [
                {"role": "system", "content": SYSTEM_PROMPT, "type": "message"},
                {"role": "user", "content": QUESTION_PROMPT.format(question=question), "type": "message"},
            ],
            "tools": tools,
        },
    }


def _read_source(path: Path) -> list[dict]:
    """Read raw rows from a ``.csv`` / ``.jsonl`` / ``.txt`` source file."""
    suffix = path.suffix.lower()
    if suffix == ".csv":
        with open(path, newline="", encoding="utf-8") as f:
            return list(csv.DictReader(f))
    if suffix in (".jsonl", ".json"):
        return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    if suffix == ".txt":
        return [{"question": line.strip()} for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    raise ValueError(f"Unsupported input extension {suffix!r} (expected .csv, .jsonl, or .txt): {path}")


def convert_file(input_file: Path, output_file: Path) -> tuple[int, int]:
    """Convert a raw Vals export to benchmark JSONL. Returns (rows, labeled rows)."""
    tools = build_tools()
    output_file.parent.mkdir(parents=True, exist_ok=True)

    count = 0
    labeled = 0
    without_rubric = 0
    criteria_total = 0
    criteria_with_modifiers = 0
    with open(output_file, "w", encoding="utf-8") as f_out:
        for raw in _read_source(input_file):
            sample = _convert_row(raw, tools)
            if sample is None:
                continue
            if sample.get("expected_answer"):
                labeled += 1
            rubric = json.loads(sample["rubric"])
            if not rubric:
                without_rubric += 1
            criteria_total += len(rubric)
            criteria_with_modifiers += sum(1 for check in rubric if check.get("modifiers"))
            f_out.write(json.dumps(sample) + "\n")
            count += 1

    # A renamed upstream rubric column would otherwise yield a dataset that still
    # runs, costs a full rollout per question, and scores every row 0.0 — which reads
    # as a bad model, not a broken dataset. Question-only sources have no rubric at
    # all, which is a legitimate dry run, so only a partial loss counts as drift.
    if count and without_rubric and without_rubric < count:
        raise ValueError(
            f"{without_rubric}/{count} rows from {input_file} have no rubric, but others do. "
            "Those rows cannot be scored. This usually means the source's rubric column was "
            "renamed or is partly empty — check the source before using this dataset."
        )

    # Same rule for `modifiers`: a criterion missing them scores at weight 1.0 and
    # never gates, so a partial loss silently mixes two scoring schemes in one run.
    # Pre-Aug-2026 sources have none at all, a supported unweighted mode.
    if criteria_with_modifiers and criteria_with_modifiers < criteria_total:
        missing = criteria_total - criteria_with_modifiers
        raise ValueError(
            f"{missing}/{criteria_total} rubric criteria from {input_file} have no 'modifiers', "
            "but others do. Those would score at severity 1.0 and never act as dealbreakers, "
            "mixing weighted and unweighted criteria in one run. Check the source; if upstream "
            "genuinely dropped modifiers for some criteria, decide the intended weight explicitly "
            "before using this dataset."
        )
    return count, labeled


def _default_source() -> Path:
    """Find the input source under ``data/`` (precedence), else download the public CSV."""
    for name in ("labeled.jsonl", "public.jsonl", "public.txt", "public.csv"):
        candidate = DATA_DIR / name
        if candidate.exists():
            print(f"Using dataset: {candidate}")
            return candidate

    # Reproducible fallback: fetch the upstream public question set.
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    dest = DATA_DIR / "public.csv"
    print(f"No local dataset found; downloading {CSV_URL} -> {dest}")
    urllib.request.urlretrieve(CSV_URL, dest)
    return dest


def prepare() -> Path:
    """``gym eval prepare`` entry point: convert the default source, return the output path."""
    out = Path(_BENCHMARK_REL_FPATH)
    count, labeled = convert_file(_default_source(), out)
    print(f"Wrote {count} benchmark samples ({labeled} labeled) to {out}")
    if labeled == 0:
        print(
            "NOTE: all samples are unlabeled — /verify will return reward 0 (dry-run). "
            "Provide data/labeled.jsonl (or a rubric column) for real scores."
        )
    return out.absolute()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Prepare / convert the Vals FABv2 benchmark data.")
    parser.add_argument(
        "--input",
        "-i",
        default=None,
        help="Explicit input file (.csv/.jsonl/.txt). If omitted, uses data/ precedence.",
    )
    parser.add_argument(
        "--output",
        "-o",
        default=None,
        help="Output JSONL path (only with --input). Default: input with a .jsonl suffix.",
    )
    args = parser.parse_args(argv)

    if args.input is None:
        prepare()
        return 0

    input_file = Path(args.input)
    if not input_file.exists():
        parser.error(f"Input file not found: {input_file}")
    output_file = Path(args.output) if args.output else input_file.with_suffix(".jsonl")

    count, labeled = convert_file(input_file, output_file)
    print(f"Converted {input_file} -> {output_file}")
    print(f"  rows: {count} ({labeled} with a synthesized/explicit expected_answer)")
    print(f"  tools: {', '.join(t['name'] for t in build_tools())}")
    print("  rubric: copied through verbatim (the scoring input; judged one criterion at a time)")
    print("  expected_answer: explicit label, else synthesized from rubric criteria (reference only)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

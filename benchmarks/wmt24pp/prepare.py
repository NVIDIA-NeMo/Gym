"""Prepare WMT24++ benchmark data.

Three steps:

1. Download the WMT24++ dataset from ``google/wmt24pp`` and write the
   interleaved benchmark JSONL (one config per en-<tgt> pair).
2. Pre-fetch the FLORES-200 SentencePiece model used for spBLEU.
3. Pre-fetch the xCOMET-XXL checkpoint AND its underlying
   xlm-roberta-xxl tokenizer into HF_HOME so the ``wmt_translation``
   resource server can run fully offline. Without this, every fresh
   ``CometActor`` resolves the tokenizer from HF Hub on startup, which
   hits the rate limiter when N actors initialize concurrently.

Per-row fields are referenced by both the prompt template
(``benchmarks/wmt24pp/prompts/default.yaml``) and the
``wmt_translation`` resource server: ``text``, ``translation``,
``source_language``, ``target_language``, ``source_lang_name``,
``target_lang_name``.

Note that we need to somehow specify the dialect/locale we want the
model to generate in. Currently, this is done by setting
``target_lang_name`` to <language> (<country>) (e.g. "Spanish (Mexico)")
"""

import argparse
import importlib.util
import json
import os
import tempfile
from pathlib import Path

from datasets import load_dataset


BENCHMARK_DIR = Path(__file__).parent
DATA_DIR = BENCHMARK_DIR / "data"
OUTPUT_FPATH = DATA_DIR / "wmt24pp_benchmark.jsonl"

HF_REPO_ID = "google/wmt24pp"

# Default COMET model used by the wmt_translation resource server.
# Pre-downloading it (plus its xlm-roberta-xxl backbone tokenizer)
# populates HF_HOME so the server can run with HF_HUB_OFFLINE=1 — no
# online tokenizer resolution at verify() time and no per-actor HF
# rate-limit retries.
COMET_MODEL = "Unbabel/XCOMET-XXL"
SPBLEU_TOKENIZER = "flores200"

# Language names generated by resources_servers/wmt_translation/scripts/
# generate_wmt24pp_language_names.py.
LANGUAGE_NAMES_PATH = DATA_DIR / "wmt24pp_language_names.json"

with LANGUAGE_NAMES_PATH.open(encoding="utf-8") as metadata_file:
    _WMT24PP_LANG_MAP: dict[str, str] = json.load(metadata_file)

# Use every supported English-to-target pair by default. Dict insertion order
# keeps the generated interleaved JSONL deterministic.
DEFAULT_TARGET_LANGUAGES = list(_WMT24PP_LANG_MAP)


def _prefetch_comet_model(model_name: str = COMET_MODEL) -> None:
    """Pre-download xCOMET-XXL + its xlm-roberta-xxl tokenizer to HF_HOME.

    ``download_model`` fetches just the COMET checkpoint files; the
    actual tokenizer + transformer backbone are pulled when
    ``load_from_checkpoint`` instantiates the model. We do both here so
    the cache is fully primed before any actor starts. Skipped silently
    if ``unbabel-comet`` is not installed in the active Python env (e.g.
    when ``prepare()`` is invoked from a venv that doesn't carry the
    server's heavy deps — the resource server's own venv will fetch on
    first use in that case).
    """
    try:
        from comet import download_model, load_from_checkpoint
    except ModuleNotFoundError as exc:
        if exc.name != "comet":
            raise
        print(f"unbabel-comet not installed; skipping {model_name} prefetch")
        return

    print(f"Pre-fetching {model_name} checkpoint...")
    ckpt_path = download_model(model_name)
    # Instantiating the model triggers the xlm-roberta-xxl tokenizer +
    # transformer download into HF_HOME. We don't keep the model object
    # — we just need the cache populated.
    print(f"Loading {model_name} once to populate xlm-roberta-xxl cache...")
    load_from_checkpoint(ckpt_path)
    print(f"{model_name} + tokenizer cached")


def _prefetch_spbleu_tokenizer() -> None:
    """Cache SacreBLEU's FLORES-200 SentencePiece model for offline scoring."""
    try:
        from sacrebleu.metrics import BLEU
    except ModuleNotFoundError as exc:
        if exc.name != "sacrebleu":
            raise
        print("sacrebleu not installed; skipping FLORES-200 spBLEU tokenizer prefetch")
        return

    if importlib.util.find_spec("sentencepiece") is None:
        print("sentencepiece not installed; skipping FLORES-200 spBLEU tokenizer prefetch")
        return

    print("Pre-fetching FLORES-200 SentencePiece tokenizer for spBLEU...")
    BLEU(tokenize=SPBLEU_TOKENIZER)
    print("FLORES-200 spBLEU tokenizer cached")


def prefetch_translation_models(*, prefetch_comet: bool = True, prefetch_spbleu: bool = True) -> None:
    """Cache the models shared by WMT-style translation benchmarks."""
    if prefetch_spbleu:
        _prefetch_spbleu_tokenizer()
    if prefetch_comet:
        _prefetch_comet_model()


def prepare(
    target_languages: list[str] | None = None,
    prefetch_comet: bool = True,
    prefetch_spbleu: bool = True,
) -> Path:
    """Download and interleave WMT24++ en-<tgt> pairs. Returns the output file path.

    If ``prefetch_spbleu`` is True (the default), caches SacreBLEU's
    FLORES-200 SentencePiece tokenizer model. If ``prefetch_comet`` is True,
    also pre-downloads xCOMET-XXL and its tokenizer into HF_HOME so the server
    can run offline. Pass ``prefetch_comet=False`` for benchmark prep on a
    machine without GPU / unbabel-comet (the cache will be populated on first
    server use instead).
    """
    if target_languages is None:
        target_languages = DEFAULT_TARGET_LANGUAGES
    else:
        target_languages = list(dict.fromkeys(target_languages))
        # check user passed in langs
        unknown = [lang for lang in target_languages if lang not in _WMT24PP_LANG_MAP]
        if unknown:
            raise ValueError(
                f"requested target languages [{','.join(unknown)}] are not in wmt24pp. "
                f"Available languages: [{','.join(list(_WMT24PP_LANG_MAP))}]"
            )

    DATA_DIR.mkdir(parents=True, exist_ok=True)

    datasets: dict = {}
    for lang in target_languages:
        print(f"Loading {HF_REPO_ID} config en-{lang}...")
        datasets[lang] = load_dataset(HF_REPO_ID, f"en-{lang}")["train"]

    file_descriptor, temp_name = tempfile.mkstemp(dir=DATA_DIR, prefix=f".{OUTPUT_FPATH.name}.")
    temp_path = Path(temp_name)
    try:
        count = 0
        with os.fdopen(file_descriptor, "w", encoding="utf-8") as fout:
            for tgt_lang in target_languages:
                for dataset_row in datasets[tgt_lang]:
                    if dataset_row["is_bad_source"]:
                        continue
                    row = {
                        "text": dataset_row["source"],
                        "translation": dataset_row["target"],
                        "source_language": "en",
                        "target_language": tgt_lang,
                        "source_lang_name": "English",
                        "target_lang_name": _WMT24PP_LANG_MAP[tgt_lang],
                    }
                    fout.write(json.dumps(row) + "\n")
                    count += 1

        prefetch_translation_models(
            prefetch_comet=prefetch_comet,
            prefetch_spbleu=prefetch_spbleu,
        )
        os.replace(temp_path, OUTPUT_FPATH)
    finally:
        temp_path.unlink(missing_ok=True)

    print(f"Wrote {count} rows to {OUTPUT_FPATH}")

    return OUTPUT_FPATH


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--target_languages",
        nargs="+",
        default=None,
        help="Target language codes (default: all supported WMT24++ locales).",
    )
    parser.add_argument(
        "--no-prefetch-comet",
        dest="prefetch_comet",
        action="store_false",
        help="Skip xCOMET-XXL checkpoint and tokenizer prefetch.",
    )
    parser.add_argument(
        "--no-prefetch-spbleu",
        dest="prefetch_spbleu",
        action="store_false",
        help="Skip the FLORES-200 SentencePiece tokenizer prefetch.",
    )
    return parser.parse_args(argv)


if __name__ == "__main__":
    args = _parse_args()
    prepare(
        target_languages=args.target_languages,
        prefetch_comet=args.prefetch_comet,
        prefetch_spbleu=args.prefetch_spbleu,
    )

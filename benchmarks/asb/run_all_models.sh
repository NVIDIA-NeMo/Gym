# Run the published ASB matrix against each model in MODELS, one model at a time.
#
# 27 conditions x 400 rows = 10,800 rollouts per model. Rows come from
# `python -m benchmarks.asb.prepare materialize` (or `... pull` for the pinned Hub copy).
#
# Every stage passes --resume, so an interrupted run picks up where it stopped.
#
# Ports are pinned away from Gym's defaults: this host runs other Gym stacks, and binding
# 11000 would either collide with them or, worse, silently evaluate against their servers.
#
# Usage:  bash benchmarks/asb/run_all_models.sh [model_key ...]
set -uo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT_DIR"

RESULTS_DIR="${RESULTS_DIR:-results/asb}"
LOG_DIR="${LOG_DIR:-${RESULTS_DIR}/logs}"
INPUT="${INPUT:-resources_servers/asb/data/all.jsonl}"
EXPECTED="${EXPECTED:-10800}"
HEAD_PORT="${HEAD_PORT:-11400}"
PORT_LOW="${PORT_LOW:-20001}"
PORT_HIGH="${PORT_HIGH:-29000}"
# Each concurrent invocation needs its own env file and port block, so several models can
# run side by side against their own endpoints instead of queueing behind one another.
ENV_YAML="${ENV_YAML:-env.yaml}"
mkdir -p "$RESULTS_DIR" "$LOG_DIR"

set -a; source "${ENV_FILE:-/Users/kruge/Documents/ChatGPT/NVIDIA/.env}"; set +a

# Per-model concurrency, because the deployments do not absorb the same load. Kimi K3's
# router opens its circuit breakers well before the others, so it gets a lower ceiling
# rather than a retry storm against a sick router.
#
# key | slug | base_url | model id | token env var | concurrency
MODELS=(
"ultra|nemotron-3-ultra-550b|https://snorkelai-fdr--ep-nvidia-nemotron-3-ultra-550b-a55b-nvfp-63eebc.us-west.modal.direct/v1|nvidia/NVIDIA-Nemotron-3-Ultra-550B-A55B-NVFP4|MODAL_PROXY_TOKEN|64"
"kimi|kimi-k3|https://snorkelai-fdr--ep-kimi-k3-server.us-west.modal.direct/v1|moonshotai/Kimi-K3|MODAL_PROXY_TOKEN|32"
"qwen|qwen3.5-122b-a10b|https://snorkelai-fdr--ep-qwen3-5-122b-a10b-fp8-server.us-west.modal.direct/v1|Qwen/Qwen3.5-122B-A10B-FP8|MODAL_PROXY_TOKEN|64"
"supervl|nemotron-3.5-super-vl|https://snorkelai-fdr--nemotron-3-5-super-vl-ea-nemotronvision.us-east.modal.direct/v1|nvidia/NVIDIA-Nemotron-3.5-Super-VL-120B-A12B-BF16|SUPER_VL_MODAL_TOKEN|64"
)

write_env_yaml() {
    local base_url="$1" model="$2" token_var="$3" concurrency="$4"
    cat > "$ENV_YAML" <<YAML
# Generated by benchmarks/asb/run_all_models.sh -- do not edit by hand.
# Ports are pinned so this stack cannot collide with another Gym stack on this host.
head_server:
  port: ${HEAD_PORT}
port_range_low: ${PORT_LOW}
port_range_high: ${PORT_HIGH}

policy_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: ${base_url}
      api_key: \${oc.env:${token_var},""}
      model: ${model}
      uses_reasoning_parser: true
      num_concurrent_requests: ${concurrency}

# ASB's Refusal Rate column comes from an LLM judge. Upstream uses gpt-4o-mini; it is
# reached through OpenRouter so no model under test ever scores itself.
asb_judge_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: https://openrouter.ai/api/v1
      api_key: \${oc.env:OPENROUTER_API_KEY_SNORKEL,""}
      model: openai/gpt-4o-mini
      uses_reasoning_parser: false
      num_concurrent_requests: 64
      # No provider pinning. ASB's attack text occasionally trips the upstream provider's
      # content filter (HTTP 400); those rows are masked by judge_failsafe and counted in
      # the coverage table rather than scored as compliant. Excluding the filtering
      # provider outright removes the only endpoint gpt-4o-mini has here and fails every
      # judge call, which is far worse than a sub-percent mask rate.
YAML
}

# Only ever kill processes belonging to THIS worktree. Other Gym stacks run on this host
# and a broad pkill would take down someone else's evaluation.
# Kill only the processes belonging to THIS invocation.
#
# Selecting by worktree path does not work: the runner invokes `.venv/bin/gym` and
# `bash benchmarks/asb/run_all_models.sh` relatively, so the absolute path never appears
# in argv. A pattern that silently matches nothing is worse than no cleanup at all --
# it leaves a previous runner alive, and the two then tear down each other's servers
# mid-eval. Select by this invocation's own ports and env file instead.
stop_servers() {
    local pid port
    for pid in $(pgrep -f "gym env start.*${ENV_YAML}" 2>/dev/null); do kill -9 "$pid" 2>/dev/null; done
    for pid in $(lsof -nP -iTCP:"${HEAD_PORT}" -sTCP:LISTEN -t 2>/dev/null); do kill -9 "$pid" 2>/dev/null; done
    for port in $(lsof -nP -iTCP -sTCP:LISTEN 2>/dev/null | awk '{print $9}' | sed 's/.*://' \
                  | grep -E '^[0-9]+$' | sort -u); do
        if [ "$port" -ge "$PORT_LOW" ] && [ "$port" -le "$PORT_HIGH" ]; then
            for pid in $(lsof -nP -iTCP:"$port" -sTCP:LISTEN -t 2>/dev/null); do
                kill -9 "$pid" 2>/dev/null
            done
        fi
    done
    sleep 5
}

start_servers() {
    local slug="$1" i
    nohup .venv/bin/gym env start \
        --config resources_servers/asb/configs/asb.yaml --config "$ENV_YAML" \
        > "${LOG_DIR}/${slug}.servers.log" 2>&1 &
    for i in $(seq 1 60); do
        sleep 5
        if grep -q "Head server finished unexpectedly" "${LOG_DIR}/${slug}.servers.log" 2>/dev/null; then
            echo "  ERROR: server stack died for ${slug}" >&2
            return 1
        fi
        if curl -s -m 2 "http://127.0.0.1:${HEAD_PORT}/" >/dev/null 2>&1; then
            sleep 20  # let the child servers finish binding
            echo "  servers up"
            return 0
        fi
    done
    echo "  ERROR: servers did not come up for ${slug}" >&2
    return 1
}

run_model() {
    local slug="$1" concurrency="$2"
    local out="${RESULTS_DIR}/${slug}.jsonl"
    local attempt status rows

    for attempt in 1 2 3 4 5 6; do
        if ! curl -s -m 3 "http://127.0.0.1:${HEAD_PORT}/" >/dev/null 2>&1; then
            echo "  [$(date +%H:%M:%S)] ${slug} head server down; restarting stack"
            stop_servers
            start_servers "$slug" || return 1
        fi
        echo "  [$(date +%H:%M:%S)] ${slug} attempt ${attempt} (concurrency ${concurrency}) -> ${out}"
        .venv/bin/gym eval run --no-serve --resume \
            --config resources_servers/asb/configs/asb.yaml --config "$ENV_YAML" \
            --agent asb_agent \
            --input "$INPUT" \
            --output "$out" \
            --num-repeats 1 \
            --concurrency "$concurrency" \
            > "${LOG_DIR}/${slug}.attempt${attempt}.log" 2>&1
        status=$?
        rows=$(wc -l < "$out" 2>/dev/null | tr -d ' ' || echo 0)
        echo "  [$(date +%H:%M:%S)] ${slug} attempt ${attempt} exit=${status} rows=${rows}/${EXPECTED}"

        if [ "$status" -eq 0 ] && [ "$rows" -ge "$EXPECTED" ]; then
            echo "  [$(date +%H:%M:%S)] ${slug} complete"
            return 0
        fi

        # A 503 from an overloaded router means back off, not push harder.
        concurrency=$(( concurrency / 2 ))
        [ "$concurrency" -lt 4 ] && concurrency=4
        echo "  [$(date +%H:%M:%S)] ${slug} backing off to concurrency ${concurrency}"
        sleep 60
    done

    echo "  [$(date +%H:%M:%S)] ${slug} INCOMPLETE after 6 attempts (${rows}/${EXPECTED})"
    return 1
}

# A second instance sharing this env file would fight the first over ports and output.
LOCK_FILE="${RESULTS_DIR}/.runner.${HEAD_PORT}.lock"
if [ -f "$LOCK_FILE" ] && kill -0 "$(cat "$LOCK_FILE" 2>/dev/null)" 2>/dev/null; then
    echo "ERROR: runner already active on head port ${HEAD_PORT} (pid $(cat "$LOCK_FILE"))." >&2
    echo "       Stop it first, or pass a different HEAD_PORT/PORT_LOW/PORT_HIGH/ENV_YAML." >&2
    exit 1
fi
echo $$ > "$LOCK_FILE"
trap 'rm -f "$LOCK_FILE"' EXIT

WANTED=("$@")
for entry in "${MODELS[@]}"; do
    IFS='|' read -r key slug base_url model token_var concurrency <<< "$entry"
    if [ ${#WANTED[@]} -gt 0 ] && [[ ! " ${WANTED[*]} " =~ " ${key} " ]]; then
        continue
    fi

    echo "==============================================================="
    echo "[$(date +%H:%M:%S)] MODEL ${key} (${model})"
    echo "==============================================================="

    write_env_yaml "$base_url" "$model" "$token_var" "$concurrency"
    stop_servers
    start_servers "$slug" || continue
    run_model "$slug" "${CONCURRENCY_OVERRIDE:-$concurrency}"
done

stop_servers
echo "[$(date +%H:%M:%S)] All requested models finished."

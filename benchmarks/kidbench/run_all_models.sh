# Run the full KIDBench grid against each model in MODELS, one model at a time.
#
# Each model gets its own server stack because the endpoints differ in base URL and, for
# the early-access deployment, in credential. Both tracks run per model: the 5,000-row
# single-turn condition grid and the 200 five-turn child-actor conversations.
#
# Every stage passes --resume, so re-running after an interruption picks up where it
# stopped rather than re-spending GPU time on rollouts that already landed.
#
# Ports are pinned away from Gym's defaults and from any other runner on this host, and
# cleanup only touches this invocation's own ports; see scripts/benchmark_runner_lib.sh for
# why a machine-wide pkill is not an option here.
#
# Usage:  bash benchmarks/kidbench/run_all_models.sh [model_key ...]
#         TRACKS=multi_turn bash benchmarks/kidbench/run_all_models.sh
#
# TRACKS selects which tracks run (all | single_turn | multi_turn). Only the multi-turn
# track uses the child actor, so a change of actor needs TRACKS=multi_turn — rerunning
# single turn would re-spend 20,000 rollouts on something the actor cannot affect.
set -uo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT_DIR"

RESULTS_DIR="${RESULTS_DIR:-results/kidbench}"
LOG_DIR="${LOG_DIR:-${RESULTS_DIR}/logs}"
# Concurrency is set per model in MODELS below, since the deployments differ in how much
# load they absorb. Set SINGLE_CONCURRENCY_OVERRIDE to force one value for every model.
TRACKS="${TRACKS:-all}"
mkdir -p "$RESULTS_DIR" "$LOG_DIR"

# This invocation's own ports. A second concurrent KIDBench run needs its own HEAD_PORT
# and port block; the env file follows the head port so the two cannot share a config.
GYM_RUNNER_NAME="kidbench"
HEAD_PORT="${HEAD_PORT:-11500}"
PORT_LOW="${PORT_LOW:-30001}"
PORT_HIGH="${PORT_HIGH:-34000}"
# Not `env.yaml`: Gym auto-loads that one and merges it after everything passed with
# --config, which would silently override the ports and the model under test. It lives
# under RESULTS_DIR because that path is already gitignored.
ENV_YAML="${ENV_YAML:-${RESULTS_DIR}/env.${HEAD_PORT}.yaml}"

source "${ROOT_DIR}/scripts/benchmark_runner_lib.sh"

# Endpoints and tokens come from a dotenv file, never from this script. ENV_FILE points at
# it; the default is the repository root, which is gitignored.
ENV_FILE="${ENV_FILE:-${ROOT_DIR}/.env}"
if [ ! -f "$ENV_FILE" ]; then
    echo "No env file at ${ENV_FILE}. Copy benchmarks/kidbench/configs/env.yaml.example for the" >&2
    echo "server wiring, and set the KIDBENCH_*_BASE_URL and token variables it documents." >&2
    exit 1
fi
set -a; source "$ENV_FILE"; set +a

# Per-model concurrency, because the deployments do not all absorb the same load. Kimi K3
# returns 503 "No available prefill workers (all circuits open or unhealthy)" well before
# the others do, so it gets a lower ceiling rather than a retry storm against a sick router.
#
# Model ids are public; base URLs are deployment-specific and are read from the environment
# by name so no endpoint is baked into a tracked file.
#
# key | slug | base-url env var | model id | token env var | single-turn concurrency
MODELS=(
"ultra|nemotron-3-ultra-550b|KIDBENCH_ULTRA_BASE_URL|nvidia/NVIDIA-Nemotron-3-Ultra-550B-A55B-NVFP4|MODAL_PROXY_TOKEN|96"
"kimi|kimi-k3|KIDBENCH_KIMI_BASE_URL|moonshotai/Kimi-K3|MODAL_PROXY_TOKEN|32"
"qwen|qwen3.5-122b-a10b|KIDBENCH_QWEN_BASE_URL|Qwen/Qwen3.5-122B-A10B-FP8|MODAL_PROXY_TOKEN|96"
"supervl|nemotron-3.5-super-vl|KIDBENCH_SUPER_VL_BASE_URL|nvidia/NVIDIA-Nemotron-3.5-Super-VL-120B-A12B-BF16|SUPER_VL_MODAL_TOKEN|96"
)

write_env_yaml() {
    local base_url="$1" model="$2" token_var="$3"
    {
    cat <<YAML
# Generated by benchmarks/kidbench/run_all_models.sh — do not edit by hand.
YAML
    gym_runner_ports_yaml
    cat <<YAML

policy_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: ${base_url}
      api_key: \${oc.env:${token_var},""}
      model: ${model}
      uses_reasoning_parser: true
      num_concurrent_requests: 64

kidbench_judge_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: https://openrouter.ai/api/v1
      api_key: \${oc.env:OPENROUTER_API_KEY,""}
      model: deepseek/deepseek-v4-pro
      uses_reasoning_parser: false
      num_concurrent_requests: 64
      extra_body:
        reasoning:
          enabled: false

# Upstream scores multi-turn with the cheaper flash model; see
# scripts/evaluation/multi_turn/deepseek.sh at the pinned revision.
kidbench_multi_turn_judge_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: https://openrouter.ai/api/v1
      api_key: \${oc.env:OPENROUTER_API_KEY,""}
      model: deepseek/deepseek-v4-flash
      uses_reasoning_parser: false
      num_concurrent_requests: 64
      extra_body:
        reasoning:
          enabled: false

# The refusal-ablated actor, deployed by benchmarks/kidbench/deploy/modal_actor.py.
# A stock instruct model refuses to stay in character on exactly the scenarios that
# matter, which flatters every model under test; see ACTOR_CHECKPOINTS in upstream_spec.
kidbench_actor_model:
  responses_api_models:
    inference_provider:
      entrypoint: app.py
      base_url: ${KIDBENCH_ACTOR_BASE_URL:?set KIDBENCH_ACTOR_BASE_URL to the deployed actor endpoint}
      api_key: \${oc.env:MODAL_PROXY_TOKEN,""}
      model: wangzhang/gemma-4-31B-it-abliterated
      uses_reasoning_parser: false
      num_concurrent_requests: 32
YAML
    } > "$ENV_YAML"
}

start_servers() {
    local slug="$1"
    nohup .venv/bin/gym env start \
        --config resources_servers/kidbench/configs/kidbench.yaml --config "$ENV_YAML" \
        > "${LOG_DIR}/${slug}.servers.log" 2>&1 &
    # Poll our own head port rather than `gym env status`: status takes no --config, so it
    # reports whatever is on the default port 11000 — possibly another runner's stack, not ours.
    gym_runner_wait_for_head "${LOG_DIR}/${slug}.servers.log"
}

run_track() {
    local slug="$1" agent="$2" input="$3" track="$4" concurrency="$5" expected="$6"
    local out="${RESULTS_DIR}/${slug}.${track}.jsonl"
    local attempt status rows

    for attempt in 1 2 3; do
        if ! gym_runner_head_is_up; then
            echo "  [$(date +%H:%M:%S)] ${slug} head server down; restarting stack"
            gym_runner_stop_servers
            start_servers "$slug" || return 1
        fi
        echo "  [$(date +%H:%M:%S)] ${slug} / ${track} attempt ${attempt} (concurrency ${concurrency}) -> ${out}"
        .venv/bin/gym eval run --no-serve --resume \
            --config resources_servers/kidbench/configs/kidbench.yaml --config "$ENV_YAML" \
            --agent "$agent" \
            --input "$input" \
            --output "$out" \
            --num-repeats 1 \
            --concurrency "$concurrency" \
            > "${LOG_DIR}/${slug}.${track}.attempt${attempt}.log" 2>&1
        status=$?
        rows=$(wc -l < "$out" 2>/dev/null || echo 0)
        echo "  [$(date +%H:%M:%S)] ${slug} / ${track} attempt ${attempt} exit=${status} rows=${rows}/${expected}"

        if [ "$status" -eq 0 ] && [ "$rows" -ge "$expected" ]; then
            echo "  [$(date +%H:%M:%S)] ${slug} / ${track} complete"
            return 0
        fi

        # A 503 from an overloaded router means back off, not push harder. Halve the
        # ceiling and let the endpoint's circuit breakers reset before trying again.
        concurrency=$(( concurrency / 2 ))
        [ "$concurrency" -lt 4 ] && concurrency=4
        echo "  [$(date +%H:%M:%S)] ${slug} / ${track} backing off to concurrency ${concurrency}"
        sleep 60
    done

    echo "  [$(date +%H:%M:%S)] ${slug} / ${track} INCOMPLETE after 3 attempts (${rows}/${expected})"
    return 1
}

gym_runner_lock "$RESULTS_DIR" || exit 1
gym_runner_clear_shadowing_env_yaml || exit 1

WANTED=("$@")
for entry in "${MODELS[@]}"; do
    IFS='|' read -r key slug base_url_var model token_var model_concurrency <<< "$entry"
    base_url="${!base_url_var:-}"
    if [ -z "$base_url" ]; then
        echo "SKIP ${key}: ${base_url_var} is not set in ${ENV_FILE}" >&2
        continue
    fi
    if [ ${#WANTED[@]} -gt 0 ] && [[ ! " ${WANTED[*]} " =~ " ${key} " ]]; then
        continue
    fi

    echo "==============================================================="
    echo "[$(date +%H:%M:%S)] MODEL ${key} (${model})"
    echo "==============================================================="

    write_env_yaml "$base_url" "$model" "$token_var"
    gym_runner_stop_servers
    start_servers "$slug" || continue

    single_concurrency="${SINGLE_CONCURRENCY_OVERRIDE:-$model_concurrency}"
    multi_concurrency=$(( single_concurrency / 2 ))
    [ "$multi_concurrency" -lt 4 ] && multi_concurrency=4

    if [ "$TRACKS" = "all" ] || [ "$TRACKS" = "single_turn" ]; then
        run_track "$slug" kidbench_simple_agent \
            resources_servers/kidbench/data/single_turn.jsonl single_turn "$single_concurrency" 5000
    fi
    if [ "$TRACKS" = "all" ] || [ "$TRACKS" = "multi_turn" ]; then
        run_track "$slug" kidbench_multi_turn_agent \
            resources_servers/kidbench/data/multi_turn.jsonl multi_turn "$multi_concurrency" 200
    fi
done

gym_runner_stop_servers
echo "[$(date +%H:%M:%S)] All requested models finished."

"""Prepare FLORES-200 benchmark data.

Three steps:

1. Download the FLORES+ dataset from ``openlanguagedata/flores_plus`` and write
   the interleaved benchmark JSONL covering English-to-X for every target
   represented in the bundled FLORES+ devtest allowlist.
2. Pre-fetch the FLORES-200 SentencePiece model used for spBLEU.
3. Pre-fetch the xCOMET-XXL checkpoint AND its underlying xlm-roberta-xxl
   tokenizer into ``HF_HOME`` so the ``wmt_translation`` resource server can
   run fully offline. Without this, every fresh ``CometActor`` resolves the
   tokenizer from HF Hub on startup, which hits the rate limiter when N
   actors initialize concurrently.

Per-row fields are referenced by both the prompt template
(``benchmarks/flores200/prompts/default.yaml``) and the ``wmt_translation``
resource server: ``text``, ``translation``, ``source_language``,
``target_language``, ``source_lang_name``, ``target_lang_name``.

Uses the same row ordering as NeMo-Skills'
``nemo_skills/dataset/flores200/prepare.py`` under the same default arguments
and split.
"""

import argparse
import json
from pathlib import Path

from datasets import load_dataset

from benchmarks.wmt24pp.prepare import prefetch_translation_models


DATA_DIR = Path(__file__).parent / "data"

HF_REPO_ID = "openlanguagedata/flores_plus"

GLOTLID_REPO_ID = "cis-lmu/glotlid"
GLOTLID_MODEL_FILENAME = "model_v3.bin"

DEFAULT_SPLIT = "devtest"

# Language metadata generated by resources_servers/wmt_translation/scripts/
# generate_flores_language_metadata.py.
LANGUAGE_NAMES_PATH = DATA_DIR / "flores_language_names.json"
DEVTEST_LANGUAGES_PATH = DATA_DIR / "flores_devtest_languages.json"

with LANGUAGE_NAMES_PATH.open(encoding="utf-8") as metadata_file:
    _FLORES_LANG_MAP: dict[str, str] = json.load(metadata_file)
with DEVTEST_LANGUAGES_PATH.open(encoding="utf-8") as metadata_file:
    _FLORES_DEVTEST_LANGUAGES = frozenset(json.load(metadata_file))

assert _FLORES_DEVTEST_LANGUAGES <= _FLORES_LANG_MAP.keys()
assert "eng_Latn" in _FLORES_DEVTEST_LANGUAGES

# Translate from English into every other devtest-capable FLORES+
# configuration by default. Dict insertion order keeps benchmark generation
# deterministic.
DEFAULT_SOURCE_LANGUAGES = ["eng_Latn"]
DEFAULT_TARGET_LANGUAGES = [
    code for code in _FLORES_LANG_MAP if code != "eng_Latn" and code in _FLORES_DEVTEST_LANGUAGES
]


def _flores_lang_code(lang: str) -> str:
    """Validate and return a complete FLORES+ configuration code."""
    if lang in _FLORES_LANG_MAP:
        return lang
    raise ValueError(
        f"Unknown FLORES+ configuration code '{lang}'. Use a complete code such as 'eng_Latn' or 'deu_Latn'."
    )


def _display_name(flores_code: str) -> str:
    try:
        return _FLORES_LANG_MAP[flores_code]
    except KeyError as exc:
        raise ValueError(
            f"No English name registered for FLORES code '{flores_code}'. Regenerate "
            "the JSON metadata with "
            "resources_servers/wmt_translation/scripts/generate_flores_language_metadata.py."
        ) from exc


def _validate_split_languages(languages: list[str], split: str) -> None:
    if split != "devtest":
        return

    unsupported = [language for language in languages if language not in _FLORES_DEVTEST_LANGUAGES]
    if unsupported:
        raise ValueError(f"These FLORES+ configurations do not provide devtest: {', '.join(unsupported)}")


def _prefetch_glotlid_model() -> None:
    """Pre-download the GlotLID model used by the FLORES verifier."""
    try:
        from huggingface_hub import hf_hub_download
    except ModuleNotFoundError as exc:
        if exc.name != "huggingface_hub":
            raise
        print("huggingface-hub not installed; skipping GlotLID prefetch")
        return

    print(f"Pre-fetching {GLOTLID_REPO_ID}/{GLOTLID_MODEL_FILENAME}...")
    hf_hub_download(
        repo_id=GLOTLID_REPO_ID,
        filename=GLOTLID_MODEL_FILENAME,
    )
    print("GlotLID model cached")


def prepare(
    languages: list[str] | None = None,
    source_languages: list[str] | None = None,
    target_languages: list[str] | None = None,
    split: str = DEFAULT_SPLIT,
    prefetch_comet: bool = True,
    prefetch_glotlid: bool = True,
    prefetch_spbleu: bool = True,
) -> Path:
    """Download and interleave FLORES+ pairs. Returns the output JSONL path.

    ``languages`` is shorthand for setting ``source_languages`` and
    ``target_languages`` to the same list (the Skills default behavior).
    Pass ``source_languages`` / ``target_languages`` explicitly to override
    one direction.

    If ``prefetch_spbleu`` is True (the default), caches SacreBLEU's
    FLORES-200 SentencePiece tokenizer model. If ``prefetch_comet`` is True,
    also pre-downloads xCOMET-XXL and its tokenizer into HF_HOME so the server
    can run offline.
    Pass ``prefetch_comet=False`` for benchmark prep on a machine without GPU
    / unbabel-comet (the cache will be populated on first server use
    instead). ``prefetch_glotlid`` similarly controls prefetching the GlotLID
    model used for FLORES language-consistency scoring.
    """
    if source_languages is None:
        source_languages = list(languages) if languages is not None else list(DEFAULT_SOURCE_LANGUAGES)
    if target_languages is None:
        target_languages = list(languages) if languages is not None else list(DEFAULT_TARGET_LANGUAGES)

    for language in source_languages:
        _flores_lang_code(language)
    for language in target_languages:
        _flores_lang_code(language)
    _validate_split_languages(source_languages, split)
    _validate_split_languages(target_languages, split)

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    output_fpath = DATA_DIR / f"flores200_{split}_benchmark.jsonl"

    all_languages = sorted(set(source_languages) | set(target_languages))
    print(f"Preparing {len(all_languages)} FLORES+ configurations for split {split!r}")

    datasets: dict = {}
    for lang in all_languages:
        print(f"Loading {HF_REPO_ID} config {lang} (split={split})...")
        datasets[lang] = load_dataset(HF_REPO_ID, lang, split=split)["text"]

    count = 0
    with output_fpath.open("w", encoding="utf-8") as fout:
        # Match Skills' nested-loop ordering: outer src, inner tgt, skip self-pairs.
        for src_lang in source_languages:
            for tgt_lang in target_languages:
                if src_lang == tgt_lang:
                    continue
                src_flores_code = _flores_lang_code(src_lang)
                tgt_flores_code = _flores_lang_code(tgt_lang)
                for src, tgt in zip(datasets[src_lang], datasets[tgt_lang], strict=True):
                    row = {
                        "text": src,
                        "translation": tgt,
                        "source_language": src_lang,
                        "target_language": tgt_flores_code,
                        "source_lang_name": _display_name(src_flores_code),
                        "target_lang_name": _display_name(tgt_flores_code),
                    }
                    fout.write(json.dumps(row) + "\n")
                    count += 1

    print(f"Wrote {count} rows to {output_fpath}")

    prefetch_translation_models(
        prefetch_comet=prefetch_comet,
        prefetch_spbleu=prefetch_spbleu,
    )
    if prefetch_glotlid:
        _prefetch_glotlid_model()

    return output_fpath


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--split",
        default=DEFAULT_SPLIT,
        choices=("dev", "devtest"),
        help="FLORES+ split to download.",
    )
    parser.add_argument(
        "--source_languages",
        default=DEFAULT_SOURCE_LANGUAGES,
        nargs="+",
        help="Complete FLORES+ configuration codes to translate from.",
    )
    parser.add_argument(
        "--target_languages",
        default=DEFAULT_TARGET_LANGUAGES,
        nargs="+",
        help="Complete FLORES+ configuration codes to translate to.",
    )
    parser.add_argument(
        "--no-prefetch-spbleu",
        dest="prefetch_spbleu",
        action="store_false",
        help="Skip the FLORES-200 SentencePiece tokenizer prefetch used by spBLEU.",
    )
    parser.add_argument(
        "--no-prefetch-comet",
        dest="prefetch_comet",
        action="store_false",
        help="Skip xCOMET-XXL prefetch (e.g. when unbabel-comet is unavailable).",
    )
    parser.add_argument(
        "--no-prefetch-glotlid",
        dest="prefetch_glotlid",
        action="store_false",
        help="Skip GlotLID model prefetch.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = _parse_args()
    prepare(
        source_languages=args.source_languages,
        target_languages=args.target_languages,
        split=args.split,
        prefetch_spbleu=args.prefetch_spbleu,
        prefetch_comet=args.prefetch_comet,
        prefetch_glotlid=args.prefetch_glotlid,
    )
